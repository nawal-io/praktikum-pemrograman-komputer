PI = 3.14

def luas_persegi_panjang(p, l):
    """Luas persegi panjang = panjang x lebar"""
    return p * l

def luas_lingkaran(r):
    """Luas lingkaran = pi x r^2"""
    return PI * (r ** 2)

def luas_segitiga(a, t):
    """Luas segitiga = 1/2 x alas x tinggi"""
    return 0.5 * a * t